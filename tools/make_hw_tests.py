"""Generate tools/test_widgets_hw.js: JS hardware tool logic (IEEE 754, number systems, Quine-McCluskey, cache, pipeline) vs Python references."""
import json
import os
import random
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from learn import refs_hw as H  # noqa: E402

rng = random.Random(55)
T = []


def add(name, expr, exp):
    T.append((name, expr, exp))


# IEEE 754
vals = [0.0, 1.0, -1.0, 0.1, -5.75, 3.14159, 1e10, 1e-10, 123456.789, 0.5, 2.5, 1.0e-40, 65504.0, -0.375, 7.0, 255.5]
vals += [rng.uniform(-1000, 1000) for _ in range(20)] + [rng.choice([1, -1]) * 2.0 ** rng.randint(-20, 20) * rng.random() for _ in range(15)]
for x in vals:
    b32, b64 = H.ieee_bits(x, 32), H.ieee_bits(x, 64)
    add("encode32 %r" % x, "LW.ieeeEncode(%r,32)" % x, b32)
    add("encode64 %r" % x, "LW.ieeeEncode(%r,64)" % x, b64)
    add("decode32 %s" % b32, "LW.ieeeDecode(%s).value" % json.dumps(b32), H.ieee_value(b32))
    add("decode64 %s" % b64, "LW.ieeeDecode(%s).value" % json.dumps(b64), H.ieee_value(b64))
add("decode inf", "LW.ieeeDecode('0' + '11111111' + '0'.repeat(23)).kind", "infinity")
add("decode nan", "LW.ieeeDecode('0' + '11111111' + '1' + '0'.repeat(22)).kind", "NaN")
add("decode denormal", "LW.ieeeDecode('0' + '00000000' + '1' + '0'.repeat(22)).kind", "denormal")

# number systems
for _ in range(40):
    bits = rng.choice([4, 5, 6, 8])
    lo, hi = -(1 << (bits - 1)), (1 << (bits - 1)) - 1
    a, b = rng.randint(lo, hi), rng.randint(lo, hi)
    r = H.add_signed(a, b, bits)
    add("add %d + %d (%d bits)" % (a, b, bits), "LW.addSigned(%d,%d,%d)" % (a, b, bits), r)
    add("twos %d (%d bits)" % (a, bits), "LW.twos(%d,%d)" % (a, bits), H.twos(a, bits))
    add("fromTwos %s" % H.twos(a, bits), "LW.fromTwos(%s)" % json.dumps(H.twos(a, bits)), a)

# Quine-McCluskey
for _ in range(60):
    n = rng.choice([2, 3, 4, 4, 5])
    allm = list(range(1 << n))
    rng.shuffle(allm)
    k = rng.randint(1, max(1, (1 << n) - 1))
    on = sorted(allm[:k])
    nd = rng.randint(0, 3) if k < (1 << n) - 3 else 0
    dc = sorted(allm[k:k + nd])
    P, terms, lits = H.min_cover(n, on, dc)
    add("qm primes n=%d on=%s dc=%s" % (n, on, dc), "LW.qm(%d,%s,%s).primes" % (n, json.dumps(on), json.dumps(dc)), P)
    add("qm cost n=%d on=%s dc=%s" % (n, on, dc), "[LW.qm(%d,%s,%s).terms, LW.qm(%d,%s,%s).literals]" % (n, json.dumps(on), json.dumps(dc), n, json.dumps(on), json.dumps(dc)), [terms, lits])

# cache
for _ in range(60):
    block = rng.choice([4, 8, 16, 32])
    assoc = rng.choice([1, 2, 4])
    sets = rng.choice([1, 2, 4, 8])
    size = block * assoc * sets
    addrs = [rng.choice([rng.randint(0, 40) * block + rng.randint(0, block - 1), rng.randint(0, 8) * block]) for _ in range(rng.randint(8, 30))]
    pol = rng.choice(["lru", "fifo"])
    h, m = H.cache_sim(addrs, size, block, assoc, pol)
    add("cache %s size=%d block=%d ways=%d %s" % (addrs, size, block, assoc, pol), "(r => [r.hits, r.misses])(LW.cacheSim(%s,{size:%d,block:%d,assoc:%d,policy:%s}))" % (json.dumps(addrs), size, block, assoc, json.dumps(pol)), [h, m])

# pipeline
REGS = ["R%d" % i for i in range(1, 7)]
for _ in range(80):
    n = rng.randint(2, 8)
    lines, ins = [], []
    for _ in range(n):
        kind = rng.choice(["alu", "alu", "load", "store", "branch"])
        if kind == "alu":
            d, a, b = rng.choice(REGS), rng.choice(REGS), rng.choice(REGS)
            lines.append("ADD %s, %s, %s" % (d, a, b))
            ins.append({"dst": d, "src": [a, b], "load": False, "branch": False})
        elif kind == "load":
            d, a = rng.choice(REGS), rng.choice(REGS)
            lines.append("LW %s, 0(%s)" % (d, a))
            ins.append({"dst": d, "src": [a], "load": True, "branch": False})
        elif kind == "store":
            a, b = rng.choice(REGS), rng.choice(REGS)
            lines.append("SW %s, 0(%s)" % (a, b))
            ins.append({"dst": None, "src": [a, b], "load": False, "branch": False})
        else:
            a, b = rng.choice(REGS), rng.choice(REGS)
            lines.append("BEQ %s, %s, L1" % (a, b))
            ins.append({"dst": None, "src": [a, b], "load": False, "branch": True})
    fwd = rng.random() < 0.5
    bp = rng.choice([0, 0, 1, 2])
    js_lines = json.dumps("\n".join(lines))
    add("pipeline fwd=%s bp=%d\n%s" % (fwd, bp, "\n".join(lines)), "LW.pipeline(%s.split('\\n').map(LW.parseInstr),{forwarding:%s,branchPenalty:%d}).total" % (js_lines, "true" if fwd else "false", bp), H.pipe_sim(ins, fwd, bp))

out = ["// AUTO-GENERATED by tools/make_hw_tests.py — JS hardware tool logic vs independent Python references.   node tools/test_widgets_hw.js",
       "require('../static/js/learn_hw.js'); const LW = globalThis.LW;",
       "const eq = (x, y) => (typeof x === 'number' && typeof y === 'number') ? (x === y || Math.abs(x - y) <= 1e-12 * Math.max(1, Math.abs(y))) : JSON.stringify(x) === JSON.stringify(y);",
       "const T = (n, c, got, exp) => console.log((c ? 'PASS ' : 'FAIL ') + n.replace(/\\n/g, ' / ') + (c ? '' : '  got=' + JSON.stringify(got) + ' expected=' + JSON.stringify(exp)));"]
for name, expr, exp in T:
    out.append("try { const got = %s; T(%s, eq(got, %s), got, %s); } catch (e) { T(%s, false, String(e), %s); }" % (expr, json.dumps(name), json.dumps(exp), json.dumps(exp), json.dumps(name), json.dumps(exp)))
open(os.path.join(ROOT, "tools", "test_widgets_hw.js"), "w", encoding="utf-8").write("\n".join(out) + "\n")
print("generated %d tests" % len(T))
