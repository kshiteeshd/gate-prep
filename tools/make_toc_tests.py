"""Generate tools/test_widgets_toc.js: JS automata / grammar logic vs independent Python reference implementations."""
import itertools
import json
import os
import random
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from learn.refs import NFA, ref_sets, ref_ll1, ref_lr0, ref_slr  # noqa: E402
rng = random.Random(33)
T = []


def add(name, expr, exp):
    T.append((name, expr, exp))


# ---------------- reference automata (written independently: dict-of-sets, brute force on strings) ----------------
def nfa_text(n):
    L = ["start %s" % n.start, "accept " + " ".join(sorted(n.acc))] + ["%s %s %s" % e for e in n.edges]
    return "\n".join(L)


for i in range(40):
    ns = rng.randint(2, 5)
    names = ["q%d" % k for k in range(ns)]
    use_eps = rng.random() < 0.35
    alpha = rng.choice([["0", "1"], ["a", "b"], ["0", "1"]])
    edges = []
    for _ in range(rng.randint(ns, ns * 3)):
        a = rng.choice(alpha + (["e"] if use_eps else []))
        edges.append((rng.choice(names), a, rng.choice(names)))
    edges = sorted(set(edges))
    if not any(a != 'e' for _, a, _ in edges):
        continue
    acc = rng.sample(names, rng.randint(1, max(1, ns // 2)))
    n = NFA(names[0], acc, edges)
    txt = nfa_text(n)
    j = json.dumps(txt)
    if len(n.alpha) < 1:
        continue
    for _ in range(4):
        w = "".join(rng.choice(n.alpha) for _ in range(rng.randint(0, 7)))
        add("accepts %r on %s" % (w, edges), "LW.nfaAccepts(LW.nfaParse(%s), %s)" % (j, json.dumps(w)), n.accepts(w))
    add("min states %s" % edges, "LW.minDfaStates(LW.nfaParse(%s))" % j, n.min_states())
    add("subset states %s" % edges, "LW.subsetDfa(LW.nfaParse(%s)).states.length" % j, len(n.dfa()[1]))
    L = rng.randint(0, 5)
    add("count len %d %s" % (L, edges), "LW.countAccepted(LW.nfaParse(%s), %d)" % (j, L), n.count(L))
    if ns <= 4:
        add("kind %s acc=%s" % (edges, sorted(acc)), "LW.langKind(LW.nfaParse(%s))" % j, n.kind())


# ---------------- reference grammar algorithms ----------------
def pgrammar(rules):
    return rules


def gen_grammar():
    nts = ["S", "A", "B", "C"][:rng.randint(2, 4)]
    terms = ["a", "b", "c", "d"][:rng.randint(2, 4)]
    rules = []
    for n in nts:
        for _ in range(rng.randint(1, 3)):
            ln = rng.choice([0, 1, 1, 2, 2, 3])
            rules.append((n, [rng.choice(terms + nts) for _ in range(ln)]))
    return nts, rules


def gtext(rules):
    out = {}
    for l, r in rules:
        out.setdefault(l, []).append(" ".join(r) if r else "e")
    return "\n".join("%s -> %s" % (l, " | ".join(a)) for l, a in out.items())


count = 0
while count < 70:
    nts, rules = gen_grammar()
    # keep the start symbol first and every non-terminal defined
    if rules[0][0] != nts[0]:
        continue
    used = {n for n, _ in rules}
    if used != set(nts):
        continue
    txt = gtext(rules)
    # round-trip: JS parses the same rule list
    j = json.dumps(txt)
    nullable, first, follow, _ = ref_sets(nts, rules)
    add("nullable\n" + txt, "LW.gSets(LW.gParse(%s)).nullable.slice().sort()" % j, sorted(n for n in nts if n in nullable))
    add("first\n" + txt, "LW.gSets(LW.gParse(%s)).first" % j, {n: sorted(first[n]) for n in nts})
    add("follow\n" + txt, "LW.gSets(LW.gParse(%s)).follow" % j, {n: sorted(follow[n]) for n in nts})
    add("ll1\n" + txt, "LW.ll1(LW.gParse(%s)).ok" % j, ref_ll1(nts, rules))
    if len(rules) <= 8:
        R, states, _ = ref_lr0(nts, rules)
        add("lr0 states\n" + txt, "LW.lr0(LW.gParse(%s)).n" % j, len(states))
        add("slr\n" + txt, "LW.slr(LW.gParse(%s)).ok" % j, ref_slr(nts, rules))
    count += 1

# textbook grammars
EXPR = "E -> E + T | T\nT -> T * F | F\nF -> ( E ) | id"
add("textbook expr LR(0) states = 12", "LW.lr0(LW.gParse(%s)).n" % json.dumps(EXPR), 12)
add("textbook expr is SLR", "LW.slr(LW.gParse(%s)).ok" % json.dumps(EXPR), True)
add("textbook L=R not SLR", "LW.slr(LW.gParse(%s)).ok" % json.dumps("S -> L = R | R\nL -> * R | id\nR -> L"), False)
add("textbook LL1 expr", "LW.ll1(LW.gParse(%s)).ok" % json.dumps("E -> T X\nX -> + T X | e\nT -> F Y\nY -> * F Y | e\nF -> ( E ) | id"), True)

out = ["// AUTO-GENERATED by tools/make_toc_tests.py — JS automata/grammar logic vs independent Python references.   node tools/test_widgets_toc.js",
       "require('../static/js/learn_toc.js'); const LW = globalThis.LW;",
       "const eq = (x, y) => JSON.stringify(x) === JSON.stringify(y);",
       "const T = (n, c, got, exp) => console.log((c ? 'PASS ' : 'FAIL ') + n.replace(/\\n/g, ' / ') + (c ? '' : '  got=' + JSON.stringify(got) + ' expected=' + JSON.stringify(exp)));"]
for name, expr, exp in T:
    out.append("try { const got = %s; T(%s, eq(got, %s), got, %s); } catch (e) { T(%s, false, String(e), %s); }" % (expr, json.dumps(name), json.dumps(exp), json.dumps(exp), json.dumps(name), json.dumps(exp)))
open(os.path.join(ROOT, "tools", "test_widgets_toc.js"), "w", encoding="utf-8").write("\n".join(out) + "\n")
print("generated %d tests" % len(T))
