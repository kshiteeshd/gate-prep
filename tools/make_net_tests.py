def crc_ref(data, gen):
    d, g = int(data, 2), int(gen, 2)
    r = len(gen) - 1
    v = d << r
    while v.bit_length() > r:
        v ^= g << (v.bit_length() - len(gen))
    return format(v, "0%db" % r) if r else ""


def mod2(v, g):
    while v and v.bit_length() >= g.bit_length():
        v ^= g << (v.bit_length() - g.bit_length())
    return v


