def dij(nodes, edges, src, directed):
    adj = {n: [] for n in nodes}
    for a, b, w in edges:
        adj[a].append((b, w))
        if not directed:
            adj[b].append((a, w))
    d = {n: float("inf") for n in nodes}
    d[src] = 0
    h = [(0, src)]
    while h:
        du, u = heapq.heappop(h)
        if du > d[u]:
            continue
        for v, w in adj[u]:
            if du + w < d[v]:
                d[v] = du + w
                heapq.heappush(h, (d[v], v))
    return d


