def tcp_ref(rounds, ss, ev):
    cwnd, out = 1, []
    for r in range(1, rounds + 1):
        out.append(cwnd)
        e = ev.get(r)
        if e == "timeout":
            ss = max(2, cwnd // 2)
            cwnd = 1
        elif e == "dup":
            ss = max(2, cwnd // 2)
            cwnd = ss
        elif cwnd < ss:
            cwnd = min(cwnd * 2, ss)
        else:
            cwnd += 1
    return out


